import re
import torch

# ==========================================
# 1. Deterministic Format Verifier (Section 2.2)
# ==========================================
def format_reward_check(completions: list[str]) -> list[float]:
    """
    Checks if the model's output strictly follows the <think>...</think><answer>...</answer> format.
    Returns 1.0 for valid format, 0.0 otherwise.
    """
    # Regex pattern: starts with <think>, has content, closes </think>,
    # then opens <answer>, has content, and ends with </answer>
    pattern = r"^<think>\n?.*?\n?</think>\n?<answer>\n?.*?\n?</answer>$"

    rewards = []
    for completion in completions:
        # re.DOTALL allows '.' to match newline characters inside the reasoning process
        match = re.match(pattern, completion.strip(), re.DOTALL)
        if match:
            rewards.append(1.0)
        else:
            rewards.append(0.0)

    return rewards

# ==========================================
# 2. Group Relative Advantage Calculation
# ==========================================
def compute_group_advantages(rewards: torch.Tensor, eps: float = 1e-8) -> torch.Tensor:
    """
    Computes group-relative advantages (A_i) without needing a Critic network.
    Formula: A_i = (r_i - mean(r)) / (std(r) + eps)

    Args:
        rewards: Tensor of shape (group_size,) containing rewards for sampled outputs.
    """
    mean_reward = rewards.mean()
    std_reward = rewards.std()

    advantages = (rewards - mean_reward) / (std_reward + eps)
    return advantages

# ==========================================
# 3. GRPO Loss Function
# ==========================================
def compute_grpo_loss(
    log_probs: torch.Tensor,
    old_log_probs: torch.Tensor,
    ref_log_probs: torch.Tensor,
    advantages: torch.Tensor,
    clip_eps: float = 0.2,
    beta: float = 0.04
) -> torch.Tensor:
    """
    Computes the GRPO loss combining the clipped surrogate objective and KL penalty.
    """
    # 1. Probability Ratio: pi_theta / pi_old
    ratio = torch.exp(log_probs - old_log_probs)

    # 2. Clipped Surrogate Objective
    surr1 = ratio * advantages
    surr2 = torch.clamp(ratio, 1.0 - clip_eps, 1.0 + clip_eps) * advantages
    policy_reward = torch.min(surr1, surr2)

    # 3. Unbiased KL Divergence Estimator (Schulman approximation used in DeepSeek-R1)
    # D_KL(pi_theta || pi_ref) = exp(log_ref - log_theta) - (log_ref - log_theta) - 1
    log_ratio_ref = ref_log_probs - log_probs
    kl_div = torch.exp(log_ratio_ref) - log_ratio_ref - 1.0

    # 4. Total Averaged Loss (Negative because optimizers minimize loss, while we want to maximize reward)
    per_sample_loss = -(policy_reward - beta * kl_div)
    return per_sample_loss.mean()

