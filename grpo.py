# 4. Real-Time Test Execution (Colab Dry Run)
# ==========================================
if __name__ == "__main__":
    # Sample group of 4 outputs generated by the model for a single math prompt
    sample_outputs = [
        "<think>\nTo find 2 + 2, I add the two numbers together to get 4.\n</think>\n<answer>4</answer>", # Perfect format
        "<think>Thinking step by step... 2 + 2 = 4</think><answer>4</answer>",                           # Valid format
        "The answer is 4.",                                                                              # No tags at all
        "<think>2 + 2 = 4</think> 4"                                                                     # Missing <answer> tag
    ]

    # Step A: Calculate Format Rewards
    raw_rewards = format_reward_check(sample_outputs)
    rewards_tensor = torch.tensor(raw_rewards, dtype=torch.float32)
    print(f"1. Format Rewards: {raw_rewards}")

    # Step B: Calculate Advantages (A_i)
    advantages = compute_group_advantages(rewards_tensor)
    print(f"2. Group Advantages (A_i): {advantages.tolist()}")

    # Step C: Dummy Log Probabilities to test GRPO Loss & AdamW step
    # Simulating a tiny linear layer as our dummy policy parameters
    dummy_model = torch.nn.Linear(10, 4)
    optimizer = torch.optim.AdamW(dummy_model.parameters(), lr=1e-4, weight_decay=0.01)

    dummy_input = torch.randn(1, 10)
    log_probs = torch.log_softmax(dummy_model(dummy_input).squeeze(0), dim=-1)
    old_log_probs = log_probs.detach() - 0.05  # Simulated old policy log_probs
    ref_log_probs = log_probs.detach() - 0.10  # Simulated reference model log_probs

    # Compute Loss and update weights
    optimizer.zero_grad()
    loss = compute_grpo_loss(log_probs, old_log_probs, ref_log_probs, advantages)
    loss.backward()
    optimizer.step()

    print(f"3. Computed GRPO Loss: {loss.item():.4f} (AdamW step completed successfully!)")